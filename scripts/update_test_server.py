#!/usr/bin/env python3
"""Serve deterministic release feeds and APKs for HydroTracker's local updater tests."""

from __future__ import annotations

import argparse
import hashlib
import json
import socket
import time
from dataclasses import dataclass
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from urllib.parse import parse_qs, quote, unquote, urlsplit


DEFAULT_ROOT = Path(__file__).resolve().parent.parent / "build" / "update-test"
DEFAULT_HOST = "0.0.0.0"
DEFAULT_PORT = 8765
DOWNLOAD_CHUNK_SIZE = 16 * 1024

SCENARIO_DESCRIPTIONS = {
    "success": "Valid newer release, APK, size and SHA-256 digest.",
    "up_to_date": "Release tag matching the installed baseline.",
    "http_error": "Return HTTP 500 instead of a release feed.",
    "invalid_json": "Return HTTP 200 with a malformed JSON body.",
    "missing_asset": "Return a release without the exact GitHub APK asset name.",
    "bad_digest": "Serve the valid APK with an all-zero SHA-256 digest.",
    "wrong_package": "Serve an APK whose application ID ends in .wrong.",
    "old_version": "Serve the installed baseline as a proposed newer update.",
    "bad_signature": "Serve an APK signed by a disposable, different key.",
    "slow_download": "Serve the valid APK in throttled chunks.",
}


@dataclass(frozen=True)
class UpdateTestConfig:
    """Version and filename metadata generated by prepare_update_test_apks.sh."""

    baseline_version_name: str
    baseline_version_code: int
    update_version_name: str
    update_version_code: int
    artefact_filenames: dict[str, str]


def load_test_config(root: Path) -> UpdateTestConfig:
    path = root / "test-config.json"
    if not path.is_file():
        raise OSError(f"Update-test manifest is missing: {path}")
    with path.open(encoding="utf-8") as source:
        data = json.load(source)
    try:
        return UpdateTestConfig(
            baseline_version_name=data["baselineVersionName"],
            baseline_version_code=int(data["baselineVersionCode"]),
            update_version_name=data["updateVersionName"],
            update_version_code=int(data["updateVersionCode"]),
            artefact_filenames=data["artefacts"],
        )
    except (KeyError, TypeError, ValueError) as error:
        raise OSError(f"Invalid update-test manifest: {path}") from error


@dataclass(frozen=True)
class ApkArtefact:
    """A prepared APK and the metadata captured when the server starts."""

    path: Path
    size: int
    sha256: str


def load_artefacts(root: Path, config: UpdateTestConfig) -> dict[str, ApkArtefact]:
    """Load only the known test APKs; never expose the test keystore or other files."""

    if not root.is_dir():
        raise OSError(f"Update-test directory does not exist: {root}")

    artefacts: dict[str, ApkArtefact] = {}
    for key, filename in config.artefact_filenames.items():
        path = root / filename
        if not path.is_file():
            raise OSError(f"Required test APK is missing: {path}")

        digest = hashlib.sha256()
        with path.open("rb") as source:
            while chunk := source.read(1024 * 1024):
                digest.update(chunk)
        artefacts[key] = ApkArtefact(
            path=path,
            size=path.stat().st_size,
            sha256=digest.hexdigest(),
        )
    return artefacts


class UpdateTestRequestHandler(BaseHTTPRequestHandler):
    """Restricted HTTP handler for release feeds and the four prepared APKs."""

    protocol_version = "HTTP/1.1"
    server_version = "HydroTrackerUpdateTest/1.0"

    def do_GET(self) -> None:  # noqa: N802 - BaseHTTPRequestHandler API
        self._dispatch(head_only=False)

    def do_HEAD(self) -> None:  # noqa: N802 - BaseHTTPRequestHandler API
        self._dispatch(head_only=True)

    def _dispatch(self, head_only: bool) -> None:
        try:
            request = urlsplit(self.path)
            if request.path == "/":
                self._serve_index(head_only)
            elif request.path == "/release.json":
                self._serve_release(request.query, head_only)
            elif request.path.startswith("/apks/"):
                self._serve_apk(request, head_only)
            else:
                self._send_bytes(
                    404,
                    b"Not found. Open / for the available test feeds.\n",
                    "text/plain; charset=utf-8",
                    head_only,
                )
        except (BrokenPipeError, ConnectionResetError):
            # A cancelled app download is an expected part of testing.
            self.log_message("Client disconnected during %s", self.path)

    def _send_bytes(
        self,
        status: int,
        body: bytes,
        content_type: str,
        head_only: bool,
        extra_headers: dict[str, str] | None = None,
    ) -> None:
        self.send_response(status)
        self.send_header("Content-Type", content_type)
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-store")
        for name, value in (extra_headers or {}).items():
            self.send_header(name, value)
        self.end_headers()
        if not head_only:
            self.wfile.write(body)

    def _base_url(self) -> str:
        # Reuse the feed request's Host so 10.0.2.2 and LAN feeds produce reachable
        # asset URLs without any per-device server configuration.
        host = self.headers.get("Host", "").strip()
        if not host:
            host = f"127.0.0.1:{self.server.server_address[1]}"
        return f"http://{host}"

    def _serve_index(self, head_only: bool) -> None:
        lines = [
            "HydroTracker update test server",
            "",
            "Available release feeds:",
        ]
        lines.extend(
            f"  {self._base_url()}/release.json?scenario={name}"
            for name in SCENARIO_DESCRIPTIONS
        )
        lines.extend(["", "APKs are linked by each feed; no directory listing is exposed.", ""])
        self._send_bytes(
            200,
            "\n".join(lines).encode("utf-8"),
            "text/plain; charset=utf-8",
            head_only,
        )

    def _serve_release(self, query: str, head_only: bool) -> None:
        scenario = parse_qs(query).get("scenario", ["success"])[0]
        if scenario not in SCENARIO_DESCRIPTIONS:
            valid_names = ", ".join(SCENARIO_DESCRIPTIONS)
            self._send_bytes(
                400,
                f"Unknown scenario: {scenario}\nAvailable scenarios: {valid_names}\n".encode("utf-8"),
                "text/plain; charset=utf-8",
                head_only,
            )
            return

        if scenario == "http_error":
            self._send_bytes(
                500,
                b"Deliberate update-test HTTP error.\n",
                "text/plain; charset=utf-8",
                head_only,
            )
            return

        if scenario == "invalid_json":
            self._send_bytes(
                200,
                f'{{"tag_name":"v{self.server.config.update_version_name}","assets":['.encode("utf-8"),
                "application/json; charset=utf-8",
                head_only,
            )
            return

        tag = (
            f"v{self.server.config.baseline_version_name}"
            if scenario == "up_to_date"
            else f"v{self.server.config.update_version_name}"
        )
        artefact_key = {
            "up_to_date": "old",
            "old_version": "old",
            "wrong_package": "wrong_package",
            "bad_signature": "bad_signature",
        }.get(scenario, "valid")
        artefact = self.server.artefacts[artefact_key]
        version_name = tag.removeprefix("v")

        if scenario == "missing_asset":
            # A non-matching F-Droid asset verifies that the updater does not download
            # the first available APK instead of the exact GitHub artefact.
            asset_name = f"HydroTracker-{version_name}-fdroid.apk"
        else:
            asset_name = f"HydroTracker-{version_name}.apk"

        download_url = (
            f"{self._base_url()}/apks/{quote(artefact.path.name)}"
        )
        if scenario == "slow_download":
            download_url += "?slow=1"

        digest = artefact.sha256
        if scenario == "bad_digest":
            digest = "0" * 64

        release = {
            "tag_name": tag,
            "name": f"HydroTracker {version_name} update test",
            "assets": [
                {
                    "name": asset_name,
                    "content_type": "application/vnd.android.package-archive",
                    "size": artefact.size,
                    "digest": f"sha256:{digest}",
                    "browser_download_url": download_url,
                }
            ],
        }
        body = json.dumps(release, indent=2).encode("utf-8") + b"\n"
        self._send_bytes(
            200,
            body,
            "application/json; charset=utf-8",
            head_only,
        )

    def _serve_apk(self, request, head_only: bool) -> None:
        filename = unquote(request.path[len("/apks/"):])
        artefact = self.server.apks_by_name.get(filename)
        if artefact is None:
            self._send_bytes(
                404,
                b"Unknown or disallowed test APK.\n",
                "text/plain; charset=utf-8",
                head_only,
            )
            return

        try:
            source = artefact.path.open("rb")
        except OSError:
            self._send_bytes(
                404,
                b"The prepared test APK is no longer available.\n",
                "text/plain; charset=utf-8",
                head_only,
            )
            return

        throttled = parse_qs(request.query).get("slow", [""])[0] == "1"
        with source:
            self.send_response(200)
            self.send_header("Content-Type", "application/vnd.android.package-archive")
            self.send_header("Content-Length", str(artefact.size))
            self.send_header("Content-Disposition", f'attachment; filename="{filename}"')
            self.send_header("Cache-Control", "no-store")
            if throttled:
                self.send_header("X-Update-Test-Throttled", "1")
            self.end_headers()

            if head_only:
                return
            while chunk := source.read(DOWNLOAD_CHUNK_SIZE):
                self.wfile.write(chunk)
                if throttled:
                    self.wfile.flush()
                    time.sleep(self.server.slow_delay)


class UpdateTestServer(ThreadingHTTPServer):
    """Threaded server so a slow APK response does not block other test requests."""

    daemon_threads = True

    def __init__(
        self,
        address: tuple[str, int],
        artefacts: dict[str, ApkArtefact],
        slow_delay: float,
        config: UpdateTestConfig,
    ) -> None:
        self.config = config
        self.artefacts = artefacts
        self.apks_by_name = {
            artefact.path.name: artefact for artefact in artefacts.values()
        }
        self.slow_delay = slow_delay
        super().__init__(address, UpdateTestRequestHandler)


def lan_ipv4_address() -> str | None:
    """Best-effort LAN address discovery; connecting a UDP socket sends no packets."""

    try:
        with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as sock:
            sock.connect(("192.0.2.1", 80))
            address = sock.getsockname()[0]
    except OSError:
        return None
    if address.startswith("127.") or address == "0.0.0.0":
        return None
    return address


def host_for_url(host: str) -> str:
    """Bracket an IPv6 literal when placing it in a URL."""

    if ":" in host and not host.startswith("["):
        return f"[{host}]"
    return host


def print_startup(server: UpdateTestServer, bind_host: str, root: Path) -> None:
    port = server.server_address[1]
    print("HydroTracker update test server")
    print(f"  Artefact root: {root}")
    print(f"  Listening on:  {bind_host}:{port}")
    print(
        f"  Baseline: {server.config.baseline_version_name} "
        f"({server.config.baseline_version_code}); "
        f"update: {server.config.update_version_name} ({server.config.update_version_code})"
    )
    print("\nRelease feed base addresses (append ?scenario=<name>):")

    if bind_host in {"0.0.0.0", "::"}:
        addresses = [
            ("Host machine", f"http://127.0.0.1:{port}/release.json"),
            ("Android emulator", f"http://10.0.2.2:{port}/release.json"),
        ]
        lan_address = lan_ipv4_address()
        if lan_address:
            addresses.append(
                ("Physical device on LAN", f"http://{lan_address}:{port}/release.json")
            )
        else:
            addresses.append(
                (
                    "Physical device on LAN",
                    f"http://<computer-LAN-IP>:{port}/release.json",
                )
            )
    else:
        addresses = [
            (
                "Configured address",
                f"http://{host_for_url(bind_host)}:{port}/release.json",
            )
        ]

    for label, address in addresses:
        print(f"  {label + ':':<25} {address}")

    print("\nScenarios:")
    for name, description in SCENARIO_DESCRIPTIONS.items():
        print(f"  {name:<15} {description}")
    print("\nAsset URLs automatically reuse each feed request's Host header.")
    print("Press Ctrl+C to stop. No external services are contacted.", flush=True)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Serve HydroTracker update-test release feeds and APKs using only Python's "
            "standard library."
        )
    )
    parser.add_argument(
        "--root",
        type=Path,
        default=DEFAULT_ROOT,
        help=f"prepared APK directory (default: {DEFAULT_ROOT})",
    )
    parser.add_argument(
        "--host",
        default=DEFAULT_HOST,
        help=f"listen address (default: {DEFAULT_HOST})",
    )
    parser.add_argument(
        "--port",
        type=int,
        default=DEFAULT_PORT,
        help=f"listen port (default: {DEFAULT_PORT})",
    )
    parser.add_argument(
        "--slow-delay",
        type=float,
        default=0.05,
        help=(
            "seconds to pause after each 16 KiB chunk for slow_download "
            "(default: 0.05)"
        ),
    )
    args = parser.parse_args()
    if not 0 <= args.port <= 65535:
        parser.error("--port must be between 0 and 65535")
    if args.slow_delay < 0:
        parser.error("--slow-delay must not be negative")
    return args


def main() -> None:
    args = parse_args()
    root = args.root.expanduser().resolve()
    try:
        config = load_test_config(root)
        artefacts = load_artefacts(root, config)
    except OSError as error:
        raise SystemExit(
            f"error: {error}\n"
            "Run ./scripts/prepare_update_test_apks.sh first, or pass --root."
        ) from error

    try:
        server = UpdateTestServer(
            (args.host, args.port),
            artefacts,
            args.slow_delay,
            config,
        )
    except OSError as error:
        raise SystemExit(f"error: could not start update test server: {error}") from error

    print_startup(server, args.host, root)
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        print("\nStopping HydroTracker update test server.")
    finally:
        server.server_close()


if __name__ == "__main__":
    main()
